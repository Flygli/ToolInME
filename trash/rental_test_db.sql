-- Тестовая БД: аренда инструментов и оборудования (аналог Авито)
-- Написано максимально переносимо: работает в SQLite и PostgreSQL.
-- id задаются явно, цены в рублях, даты в формате 'YYYY-MM-DD'.

DROP TABLE IF EXISTS item_attributes;
DROP TABLE IF EXISTS items;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS brands;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS cities;

CREATE TABLE cities (
    id   INTEGER PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE categories (
    id   INTEGER PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE brands (
    id      INTEGER PRIMARY KEY,
    name    TEXT NOT NULL,
    country TEXT
);

CREATE TABLE users (
    id         INTEGER PRIMARY KEY,
    name       TEXT NOT NULL,
    phone      TEXT,
    city_id    INTEGER REFERENCES cities(id),
    rating     REAL,            -- 1.0 .. 5.0
    registered TEXT
);

CREATE TABLE items (
    id             INTEGER PRIMARY KEY,
    owner_id       INTEGER NOT NULL REFERENCES users(id),
    category_id    INTEGER NOT NULL REFERENCES categories(id),
    brand_id       INTEGER REFERENCES brands(id),
    city_id        INTEGER NOT NULL REFERENCES cities(id),
    title          TEXT NOT NULL,
    model          TEXT,
    description    TEXT,
    price_per_day  INTEGER NOT NULL,
    price_per_week INTEGER,
    deposit        INTEGER,                 -- залог
    condition      TEXT,                    -- new / good / used
    year           INTEGER,
    delivery       INTEGER DEFAULT 0,       -- 1 = есть доставка
    is_available   INTEGER DEFAULT 1,       -- 1 = свободен
    created_at     TEXT
);

-- Произвольные параметры (у каждого инструмента свой набор)
CREATE TABLE item_attributes (
    id      INTEGER PRIMARY KEY,
    item_id INTEGER NOT NULL REFERENCES items(id),
    name    TEXT NOT NULL,
    value   TEXT NOT NULL,
    unit    TEXT
);

